/// One round for one class. `stockMint` must be that class's mint.
export function runRoundIx({ cranker, classId, stockMint, tokenProgram = TOKEN_PROGRAM_ID }) {
  const engine = enginePda();
  return new TransactionInstruction({
    programId: PROGRAM_ID,
    keys: [
      { pubkey: new PublicKey(cranker), isSigner: true, isWritable: false },
      { pubkey: engine, isSigner: false, isWritable: true },
      { pubkey: new PublicKey(stockMint), isSigner: false, isWritable: false },
      { pubkey: ataFor(stockMint, engine, tokenProgram), isSigner: false, isWritable: false },
      // Last, matching the RunRound struct. The program needs it to derive the
      // associated-token address the same way this client just did.
      { pubkey: new PublicKey(tokenProgram), isSigner: false, isWritable: false },
    ],
    data: Buffer.concat([Buffer.from(DISC.runRound), u8(classId)]),
  });
}

