/// Fixed-point scale for the per-NFT accumulator. Must match the program.
export const ACC_SCALE = 10n ** 12n;

/// ATAs here are always for PDA owners (the engine, and each vault), so the
/// off-curve path is the normal case rather than the exception.
export function ataFor(mint, owner, tokenProgram = TOKEN_PROGRAM_ID) {
  return PublicKey.findProgramAddressSync(
    [new PublicKey(owner).toBuffer(), new PublicKey(tokenProgram).toBuffer(), new PublicKey(mint).toBuffer()],
    ASSOCIATED_TOKEN_PROGRAM_ID,
  )[0];
}

