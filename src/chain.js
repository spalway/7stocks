/// Layout: authority, 7x pubkey stocks, 7x u128 acc, 7x u64 outstanding,
/// 7x u32 class_count, 7x i64 last_round, i64 min_interval, u64 dust_floor, u8.
export function decodeEngine(data) {
  const r = readerFor(data);
  const authority = r.pubkey();
  const stocks = times(CLASS_COUNT, r.pubkey);
  const accPerNft = times(CLASS_COUNT, r.u128);
  const outstanding = times(CLASS_COUNT, r.u64);
  const classCount = times(CLASS_COUNT, r.u32);
  const lastRound = times(CLASS_COUNT, r.i64);
  const minInterval = r.i64();
  const dustFloor = r.u64();
  const bump = r.u8();
  return { authority, stocks, accPerNft, outstanding, classCount, lastRound, minInterval, dustFloor, bump };
}

/// Layout: asset, u8 class, u128 stamp, u8 bump.
export function decodeCeo(data) {
  const r = readerFor(data);
  const asset = r.pubkey();
  const classId = r.u8();
  const stamp = r.u128();
  const bump = r.u8();
  return { asset, classId, stamp, bump };
}

/// What one NFT is owed of its class's stock, undelivered — the same arithmetic
/// the program runs in `settle`, so the UI can show it without a crank.
export function owedFor(engine, ceo) {
  const acc = engine.accPerNft[ceo.classId];
  const delta = acc > ceo.stamp ? acc - ceo.stamp : 0n;
  return delta / ACC_SCALE;
}

/// Every registered CEO. One PDA per NFT, so a single program scan finds them.
export async function fetchAllCeos(connection) {
  const accounts = await connection.getProgramAccounts(PROGRAM_ID, {
    filters: [{ memcmp: { offset: 0, bytes: CEO_ACCOUNT_FILTER } }],
  });
  return accounts.map(({ pubkey, account }) => ({ pda: pubkey, ...decodeCeo(account.data) }));
}

/// Ceo PDAs for many assets in one call.
export async function fetchCeoStates(connection, assets) {
  if (!assets.length) return new Map();
  const accounts = await connection.getMultipleAccountsInfo(assets.map(ceoPda));
  return new Map(assets.map((asset, i) => [
    new PublicKey(asset).toBase58(),
    accounts[i] ? decodeCeo(accounts[i].data) : null,
  ]));
}

/// Each vault's balance of ITS OWN class's stock, in as few RPC calls as
/// possible. An NFT only ever holds one stock, so this is one ATA per vault —
/// not a grid. Token account layout: mint(32) owner(32) amount(u64 LE @64).
export async function fetchVaultBalances(connection, holders, engine, tokenProgram = TOKEN_PROGRAM_ID) {
  // holders: [{ asset, classId }]
  if (!holders.length) return new Map();
  const atas = holders.map((h) => ataFor(engine.stocks[h.classId], vaultPda(h.asset), tokenProgram));
  const out = new Map();
  for (let i = 0; i < atas.length; i += 100) {
    const slice = await connection.getMultipleAccountsInfo(atas.slice(i, i + 100));
    slice.forEach((account, j) => {
      const h = holders[i + j];
      const raw = account ? Buffer.from(account.data.subarray(64, 72)).readBigUInt64LE() : 0n;
      // Base units as a decimal string — a BigInt in React state breaks
      // serialisation, and a float cannot sweep 100% exactly.
      out.set(new PublicKey(h.asset).toBase58(), raw.toString());
    });
  }
  return out;
}

// ------------------------------------------------------------------- sweep
//
// Pulling tokens out of a vault needs no program of ours. Core's `ExecuteV1`
// lets the *current owner* of an asset make that asset's signer PDA sign one
// arbitrary instruction, and the signer PDA is the vault. So a sweep is a
// plain SPL transfer whose authority happens to be the vault, wrapped in
// Execute and authorised by the NFT. The right to spend it IS ownership of the
// NFT, checked by Core, and it moves to the buyer the instant the NFT sells.

const CORE_EXECUTE_DISCRIMINATOR = 31;
const TOKEN_TRANSFER_CHECKED = 12;

export function transferCheckedIx({ source, mint, destination, authority, amount, decimals, tokenProgram = TOKEN_PROGRAM_ID }) {
  const data = Buffer.alloc(10);
  data.writeUInt8(TOKEN_TRANSFER_CHECKED, 0);
  data.writeBigUInt64LE(BigInt(amount), 1);
  data.writeUInt8(decimals, 9);
  return new TransactionInstruction({
    programId: new PublicKey(tokenProgram),
    keys: [
      { pubkey: new PublicKey(source), isSigner: false, isWritable: true },
      { pubkey: new PublicKey(mint), isSigner: false, isWritable: false },
      { pubkey: new PublicKey(destination), isSigner: false, isWritable: true },
      { pubkey: new PublicKey(authority), isSigner: false, isWritable: false },
    ],
    data,
  });
}

/// Wrap one instruction so the asset's vault signs it. The vault is marked
/// non-signer in BOTH places it appears — no signature for it exists; Core sets
/// the flag itself via invoke_signed. Marking it a signer here would make the
/// wallet ask for a signature nobody can produce.
export function coreExecuteIx({ asset, collection, owner, payer, inner }) {
  const length = Buffer.alloc(4);
  length.writeUInt32LE(inner.data.length);
  return new TransactionInstruction({
    programId: MPL_CORE_PROGRAM_ID,
    keys: [
      { pubkey: new PublicKey(asset), isSigner: false, isWritable: true },
      { pubkey: new PublicKey(collection), isSigner: false, isWritable: true },
      { pubkey: vaultPda(asset), isSigner: false, isWritable: false },
      { pubkey: new PublicKey(payer ?? owner), isSigner: true, isWritable: true },
      { pubkey: new PublicKey(owner), isSigner: true, isWritable: false },
      { pubkey: SystemProgram.programId, isSigner: false, isWritable: false },
      { pubkey: new PublicKey(inner.programId), isSigner: false, isWritable: false },
      ...inner.keys.map((k) => ({ ...k, isSigner: false })),
    ],
    data: Buffer.concat([Buffer.from([CORE_EXECUTE_DISCRIMINATOR]), length, inner.data]),
  });
}

/// Move `amount` raw units of a stock from an NFT's vault to its owner.
export function sweepIx({ asset, collection, owner, mint, amount, decimals, tokenProgram = TOKEN_PROGRAM_ID }) {
  const vault = vaultPda(asset);
  return coreExecuteIx({
    asset, collection, owner,
    inner: transferCheckedIx({
      source: ataFor(mint, vault, tokenProgram),
      mint,
      destination: ataFor(mint, owner, tokenProgram),
      authority: vault,
      amount, decimals, tokenProgram,
    }),
  });
}

